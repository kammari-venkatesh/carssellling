export function getCarImages(make: string, index: number): string[] {
  const pool = CAR_IMAGES[make] ?? DEFAULT_IMAGES
  const primary = pool[index % pool.length]
  const secondary = pool[(index + 1) % pool.length]
  const tertiary = pool[(index + 2) % pool.length]
  return [primary, secondary, tertiary, primary]
}

export function getCarImageAlt(make: string, model: string, year: number): string {
  return `${make} ${model} ${year}`
}
